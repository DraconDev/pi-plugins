// pi-vpn — ephemeral Pi-only VPN via WireGuard + wireproxy
//
// Lives only while pi runs. No background service, no system-wide VPN.
// Pi AI HTTPS calls go through local HTTP proxy (wireproxy) whose traffic
// exits via WireGuard (Proton US by default). Auto-expires after ~7 days.
// Chrome / other apps are untouched.
//
// Env:
//   PI_VPN_CONF       path to raw WireGuard .conf (default ~/.config/pi-vpn/proton.conf)
//   PI_VPN_HTTP_PORT  default 19091
//   PI_VPN_SOCKS_PORT default 19090
//
// Files in ~/.config/pi-vpn/:
//   proton.conf     — raw WG config from Proton dashboard (you place it)
//   wireproxy.conf  — generated (WGConfig + Socks5 + http)
//   expires-at      — epoch seconds (7-day expiry)
//   wireproxy.pid   — pid when running
//
// Wrapper ~/.local/bin/pi-vpn exports HTTP_PROXY before pi boots so Pi's
// undici dispatcher routes AI calls via wireproxy. Running plain `pi` also
// auto-starts wireproxy via this extension but undici may not pick it up
// until next launch — prefer `pi-vpn` for guaranteed AI coverage.

import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";
import * as fs from "node:fs";
import * as path from "node:path";
import * as os from "node:os";

const STATUS_KEY = "pi-vpn";
const WIDGET_KEY = "pi-vpn";

const HOME = os.homedir();
const CONFIG_DIR = process.env.PI_VPN_DIR ?? path.join(HOME, ".config", "pi-vpn");
const PROTON_CONF = process.env.PI_VPN_CONF ?? path.join(CONFIG_DIR, "proton.conf");
const WIREPROXY_CONF = path.join(CONFIG_DIR, "wireproxy.conf");
const EXPIRES_AT_FILE = path.join(CONFIG_DIR, "expires-at");
const PID_FILE = path.join(CONFIG_DIR, "wireproxy.pid");

const HTTP_PORT = Number(process.env.PI_VPN_HTTP_PORT ?? 19091);
const SOCKS_PORT = Number(process.env.PI_VPN_SOCKS_PORT ?? 19090);
const HTTP_PROXY_URL = `http://127.0.0.1:${HTTP_PORT}`;
const EXPIRY_DAYS = 7;
const EXPIRY_SECONDS = EXPIRY_DAYS * 24 * 60 * 60;

function ensureDir() {
  fs.mkdirSync(CONFIG_DIR, { recursive: true, mode: 0o700 });
}

function readExpiry(): number | null {
  try {
    const raw = fs.readFileSync(EXPIRES_AT_FILE, "utf8").trim();
    const n = Number(raw);
    return Number.isFinite(n) && n > 0 ? n : null;
  } catch {
    return null;
  }
}

function writeExpiry(expiresAtSec: number) {
  ensureDir();
  fs.writeFileSync(EXPIRES_AT_FILE, String(Math.floor(expiresAtSec)), { mode: 0o600 });
}

function isExpired(): { expired: boolean; expiresAt: number | null; remainingSec: number | null } {
  const exp = readExpiry();
  if (exp == null) return { expired: true, expiresAt: null, remainingSec: null };
  const now = Math.floor(Date.now() / 1000);
  return { expired: now >= exp, expiresAt: exp, remainingSec: exp - now };
}

function refreshExpiry() {
  const exp = Math.floor(Date.now() / 1000) + EXPIRY_SECONDS;
  writeExpiry(exp);
  return exp;
}

function humanRemaining(sec: number | null): string {
  if (sec == null) return "unknown";
  if (sec <= 0) return "expired";
  const d = Math.floor(sec / 86400);
  const h = Math.floor((sec % 86400) / 3600);
  if (d > 0) return `${d}d ${h}h left`;
  if (h > 0) return `${h}h left`;
  const m = Math.ceil(sec / 60);
  return `${m}m left`;
}

function ensureWireproxyConf(): { ok: boolean; msg: string } {
  if (!fs.existsSync(PROTON_CONF)) {
    return {
      ok: false,
      msg: `Missing WireGuard config at ${PROTON_CONF}. Download from Proton dashboard (account.protonvpn.com/downloads) and save it there, then run /vpn refresh or use pi-vpn wrapper.`
    };
  }
  ensureDir();
  const content = [
    `# generated by pi-vpn — do not edit manually (run /vpn refresh to regenerate)`,
    `WGConfig = ${PROTON_CONF}`,
    ``,
    `[Socks5]`,
    `BindAddress = 127.0.0.1:${SOCKS_PORT}`,
    ``,
    `[http]`,
    `BindAddress = 127.0.0.1:${HTTP_PORT}`,
    ``
  ].join("\n");
  fs.writeFileSync(WIREPROXY_CONF, content, { mode: 0o600 });
  return { ok: true, msg: `wireproxy.conf generated (HTTP ${HTTP_PORT}, SOCKS5 ${SOCKS_PORT})` };
}

function findWireproxy(): string | null {
  // Prefer PATH, fallback to nix store path if discoverable
  try {
    const out = fs.readdirSync("/nix/store").find((e) => e.includes("-wireproxy-") && e.endsWith("/bin/wireproxy"));
    void out;
  } catch {}
  // We use pi.exec to probe; this sync check is just a hint. Actual probe runs async.
  return null;
}

async function probeWireproxy(pi: any): Promise<{ found: boolean; cmd: string[] }> {
  const probes: string[][] = [
    ["which", ["wireproxy"]],
    ["command", ["-v", "wireproxy"]]
  ];
  for (const [c, a] of probes) {
    try {
      const r = await pi.exec(c, a, { timeout: 2000 });
      const out = (r.stdout ?? "").trim();
      if (out.includes("wireproxy") || r.code === 0) {
        return { found: true, cmd: ["wireproxy"] };
      }
    } catch {}
  }
  // Try nix-shell wrapper if available
  try {
    const r = await pi.exec("nix-shell", ["-p", "wireproxy", "--run", "command -v wireproxy"], { timeout: 15000 });
    if (r.code === 0 && (r.stdout ?? "").trim().length > 0) {
      return { found: true, cmd: ["nix-shell", "-p", "wireproxy", "--run", "wireproxy"] };
    }
  } catch {}
  // Try direct /nix/store glob via bash
  try {
    const r = await pi.exec("bash", ["-lc", "ls /nix/store/*-wireproxy-*/bin/wireproxy 2>/dev/null | head -1"], { timeout: 5000 });
    const p = (r.stdout ?? "").trim();
    if (p) return { found: true, cmd: [p] };
  } catch {}
  return { found: false, cmd: ["wireproxy"] };
}

function pidAlive(pid: number): boolean {
  try {
    process.kill(pid, 0);
    return true;
  } catch {
    return false;
  }
}

function readPid(): number | null {
  try {
    const n = Number(fs.readFileSync(PID_FILE, "utf8").trim());
    return Number.isFinite(n) && n > 0 ? n : null;
  } catch {
    return null;
  }
}

async function isWireproxyRunning(pi: any): Promise<boolean> {
  const pid = readPid();
  if (pid && pidAlive(pid)) return true;
  // Probe listening ports via bash
  try {
    const r = await pi.exec("bash", ["-lc", `ss -tln 2>/dev/null | grep -q :${HTTP_PORT} && echo yes || echo no`], { timeout: 3000 });
    return (r.stdout ?? "").trim() === "yes";
  } catch {
    return false;
  }
}

let startedByExtension = false;

async function startWireproxy(pi: any, ctx: any): Promise<{ ok: boolean; msg: string }> {
  const { expired, expiresAt } = isExpired();
  if (expired) {
    return { ok: false, msg: `VPN expired (expires-at ${expiresAt ? new Date(expiresAt * 1000).toISOString() : "missing"}). Run /vpn refresh to extend 7 days.` };
  }
  const conf = ensureWireproxyConf();
  if (!conf.ok) return conf;

  if (await isWireproxyRunning(pi)) {
    return { ok: true, msg: `wireproxy already running on ${HTTP_PROXY_URL}` };
  }

  const probe = await probeWireproxy(pi);
  if (!probe.found) {
    return {
      ok: false,
      msg: `wireproxy not found. Install via: nix-shell -p wireproxy  OR  go install github.com/octeep/wireproxy/cmd/wireproxy@latest  OR  npm i -g wireproxy. See ~/.config/pi-vpn/`
    };
  }

  // Kill stale pidfile
  const stale = readPid();
  if (stale && !pidAlive(stale)) {
    try { fs.unlinkSync(PID_FILE); } catch {}
  }

  // Start via bash background (wireproxy -d fails in this sandbox with
  // "open /dev/null: permission denied" — background & works reliably).
  // Log goes to ~/.config/pi-vpn/wireproxy.log, pid captured via $!.
  const LOG_FILE = path.join(CONFIG_DIR, "wireproxy.log");
  let bin: string;
  if (probe.cmd[0] === "nix-shell") {
    bin = "wireproxy";
  } else {
    bin = probe.cmd[0]!;
  }
  const wrap = probe.cmd[0] === "nix-shell"
    ? `nix-shell -p wireproxy --run "wireproxy -c ${WIREPROXY_CONF}"`
    : `${bin} -c ${WIREPROXY_CONF}`;
  const cmdStr = `nohup ${wrap} > ${LOG_FILE} 2>&1 & echo $!`;

  try {
    const r = await pi.exec("bash", ["-lc", cmdStr], { timeout: 8000 });
    if (r.code !== 0) {
      return { ok: false, msg: `wireproxy failed: ${(r.stderr ?? r.stdout ?? "").trim().slice(0, 400)}` };
    }
    // $! gives pid directly; fallback to pgrep
    await new Promise((res) => setTimeout(res, 600));
    let pid = Number(((r.stdout ?? "").trim().split(/\s+/).pop() ?? ""));
    if (!Number.isFinite(pid) || pid <= 0) {
      const pgrep = await pi.exec("bash", ["-lc", `pgrep -f "[w]ireproxy -c ${WIREPROXY_CONF}" | head -1 || echo ""`], { timeout: 3000 });
      pid = Number((pgrep.stdout ?? "").trim());
    }
    if (Number.isFinite(pid) && pid > 0) {
      fs.writeFileSync(PID_FILE, String(pid), { mode: 0o600 });
      startedByExtension = true;
    }
    // Poll for listening port (nix-shell first run can take 10-30s)
    let running = false;
    for (let i = 0; i < 60; i++) {
      if (await isWireproxyRunning(pi)) { running = true; break; }
      await new Promise((r) => setTimeout(r, 500));
    }
    if (running) {
      // Expose to subsequent fetch in this process (undici dispatcher already created at boot,
      // but wrapper pi-vpn sets it before boot; this helps in-process / bash tools)
      process.env.HTTP_PROXY = HTTP_PROXY_URL;
      process.env.HTTPS_PROXY = HTTP_PROXY_URL;
      process.env.http_proxy = HTTP_PROXY_URL;
      process.env.https_proxy = HTTP_PROXY_URL;
      process.env.NO_PROXY = "127.0.0.1,localhost";
      process.env.no_proxy = "127.0.0.1,localhost";
      return { ok: true, msg: `wireproxy started (pid ${pid || "?"}) HTTP ${HTTP_PORT} SOCKS5 ${SOCKS_PORT}` };
    }
    return { ok: false, msg: `wireproxy did not open port ${HTTP_PORT} after 30s. Check ${path.join(CONFIG_DIR, "wireproxy.log")} / ${PROTON_CONF}` };
  } catch (e: any) {
    return { ok: false, msg: `wireproxy start error: ${e?.message ?? String(e)}` };
  }
}

async function stopWireproxy(pi: any): Promise<{ ok: boolean; msg: string }> {
  const pid = readPid();
  if (pid && pidAlive(pid)) {
    try {
      process.kill(pid, "SIGTERM");
      await new Promise((r) => setTimeout(r, 500));
      try { fs.unlinkSync(PID_FILE); } catch {}
      const { expired } = { expired: false };
      void expired;
      return { ok: true, msg: `wireproxy stopped (pid ${pid})` };
    } catch (e: any) {
      return { ok: false, msg: `Failed to stop pid ${pid}: ${e?.message}` };
    }
  }
  // Fallback pkill
  try {
    const r = await pi.exec("bash", ["-lc", `pkill -f "[w]ireproxy -c ${WIREPROXY_CONF}" || true; echo done`], { timeout: 3000 });
    void r;
    try { fs.unlinkSync(PID_FILE); } catch {}
    return { ok: true, msg: "wireproxy stop attempted (no pidfile)" };
  } catch (e: any) {
    return { ok: false, msg: `stop error: ${e?.message}` };
  }
}

async function getEgressIP(pi: any): Promise<{ ip: string | null; viaProxy: boolean; err?: string }> {
  // Try curl via proxy first, then direct
  const urls = ["https://ifconfig.me/ip", "https://api.ipify.org"];
  for (const url of urls) {
    try {
      const r = await pi.exec("bash", ["-lc", `curl -s --max-time 8 -x ${HTTP_PROXY_URL} ${url} || curl -s --max-time 8 ${url}`], { timeout: 10000 });
      const ip = (r.stdout ?? "").trim().split(/\s+/)[0];
      if (ip && /^\d+\.\d+\.\d+\.\d+$/.test(ip)) return { ip, viaProxy: true };
    } catch {}
  }
  // fetch fallback (respects env proxy if set)
  try {
    const ctrl = new AbortController();
    const t = setTimeout(() => ctrl.abort(), 8000);
    const res = await fetch("https://ifconfig.me/ip", { signal: ctrl.signal });
    clearTimeout(t);
    if (res.ok) return { ip: (await res.text()).trim(), viaProxy: !!process.env.HTTP_PROXY };
  } catch (e: any) {
    return { ip: null, viaProxy: false, err: e?.message };
  }
  return { ip: null, viaProxy: false, err: "unreachable" };
}

function updateWidget(ctx: any, lines: string[]) {
  try {
    ctx.ui.setWidget(WIDGET_KEY, lines);
  } catch {}
}
function updateStatus(ctx: any, text: string | undefined) {
  try {
    ctx.ui.setStatus(STATUS_KEY, text);
  } catch {}
}

export default function (pi: ExtensionAPI) {
  pi.registerCommand("vpn", {
    description: "Pi-only ephemeral VPN (WireGuard + wireproxy) — status, on/off, refresh, check-ip",
    handler: async (args: string, ctx: any) => {
      const raw = (args ?? "").trim().toLowerCase();
      const [sub, ...rest] = raw.split(/\s+/).filter(Boolean);
      const cmd = sub || "status";

      if (cmd === "help" || cmd === "--help") {
        const help = [
          "Pi-only VPN — /vpn <status|on|off|refresh|check-ip|help>",
          "",
          "  /vpn status     show expiry, wireproxy state, egress IP, proxy URL",
          "  /vpn on         start wireproxy (respects 7-day expiry)",
          "  /vpn off        stop wireproxy",
          "  /vpn refresh    regenerate wireproxy.conf + extend expiry 7d",
          "  /vpn check-ip   query egress IP (via proxy if running)",
          "",
          `Config dir: ${CONFIG_DIR}`,
          `  proton.conf should be raw Proton WireGuard .conf`,
          `  wireproxy.conf is generated from proton.conf`,
          `  HTTP ${HTTP_PROXY_URL}  SOCKS5 socks://127.0.0.1:${SOCKS_PORT}`,
          "",
          "Prefer launching via: pi-vpn  (sets HTTP_PROXY before pi boots so AI calls use it)",
        ].join("\n");
        ctx.ui.notify(help, "info");
        return;
      }

      if (cmd === "status") {
        const { expired, expiresAt, remainingSec } = isExpired();
        const running = await isWireproxyRunning(pi);
        const ip = await getEgressIP(pi);
        const lines = [
          `VPN: ${expired ? "EXPIRED" : running ? "ON" : "OFF"}`,
          `Expiry: ${expiresAt ? new Date(expiresAt * 1000).toISOString() : "(missing)"} — ${humanRemaining(remainingSec)}`,
          `Proxy: ${HTTP_PROXY_URL} (HTTP) / socks://127.0.0.1:${SOCKS_PORT}`,
          `wireproxy: ${running ? "running" : "not running"} — conf ${WIREPROXY_CONF}`,
          `proton.conf: ${fs.existsSync(PROTON_CONF) ? "present" : "MISSING at " + PROTON_CONF}`,
          `Egress: ${ip.ip ?? "(unknown)"} ${ip.viaProxy ? "(via proxy)" : ""}`,
          `Env HTTP_PROXY=${process.env.HTTP_PROXY ?? "(unset)"}`,
        ];
        updateWidget(ctx, ["VPN " + (expired ? "expired" : running ? "ON" : "OFF"), `expiry ${humanRemaining(remainingSec)}`, `egress ${ip.ip ?? "?"}`, `GET /vpn help`]);
        updateStatus(ctx, expired ? "vpn:expired" : running ? "vpn:on" : "vpn:off");
        ctx.ui.notify(lines.join("\n"), expired ? "warning" : "info");
        return;
      }

      if (cmd === "on") {
        const r = await startWireproxy(pi, ctx);
        ctx.ui.notify(r.msg, r.ok ? "info" : "error");
        const { expired, remainingSec } = isExpired();
        updateStatus(ctx, expired ? "vpn:expired" : r.ok ? "vpn:on" : "vpn:off");
        updateWidget(ctx, ["VPN " + (r.ok ? "ON" : "OFF"), `expiry ${humanRemaining(remainingSec)}`, `GET /vpn status`]);
        return;
      }

      if (cmd === "off") {
        const r = await stopWireproxy(pi);
        delete process.env.HTTP_PROXY;
        delete process.env.HTTPS_PROXY;
        delete process.env.http_proxy;
        delete process.env.https_proxy;
        ctx.ui.notify(r.msg, r.ok ? "info" : "error");
        updateStatus(ctx, "vpn:off");
        updateWidget(ctx, ["VPN OFF"]);
        return;
      }

      if (cmd === "refresh") {
        const c = ensureWireproxyConf();
        const exp = refreshExpiry();
        const r = await startWireproxy(pi, ctx);
        const msg = `${c.msg}\nExpiry extended to ${new Date(exp * 1000).toISOString()} (${EXPIRY_DAYS}d)\n${r.msg}`;
        ctx.ui.notify(msg, r.ok || c.ok ? "info" : "error");
        return;
      }

      if (cmd === "check-ip" || cmd === "ip") {
        ctx.ui.notify("Checking egress IP via proxy…", "info");
        const ip = await getEgressIP(pi);
        ctx.ui.notify(ip.ip ? `Egress: ${ip.ip} ${ip.viaProxy ? "(via wireproxy)" : "(direct)"}` : `Egress check failed: ${ip.err ?? "unknown"}`, ip.ip ? "info" : "error");
        return;
      }

      if (cmd === "expiry") {
        const { expired, expiresAt, remainingSec } = isExpired();
        ctx.ui.notify(`Expires: ${expiresAt ? new Date(expiresAt * 1000).toISOString() : "missing"} — ${humanRemaining(remainingSec)} — expired=${expired}. ${rest.length ? "Run /vpn refresh to extend." : ""}`, expired ? "warning" : "info");
        return;
      }

      ctx.ui.notify(`Unknown /vpn arg: ${raw}\nUsage: /vpn [status|on|off|refresh|check-ip|help]`, "warning");
    }
  });

  pi.on("session_start", async (_event: any, ctx: any) => {
    const { expired, expiresAt, remainingSec } = isExpired();
    // Don't auto-create expiry on first run if no proton.conf — just show guidance
    if (!fs.existsSync(PROTON_CONF)) {
      updateStatus(ctx, "vpn:no-conf");
      updateWidget(ctx, ["VPN: no conf", `put proton.conf in ${CONFIG_DIR}`, `/vpn help`]);
      return;
    }
    if (expired) {
      updateStatus(ctx, "vpn:expired");
      updateWidget(ctx, ["VPN EXPIRED", `expired ${expiresAt ? new Date(expiresAt * 1000).toDateString() : ""}`, `/vpn refresh`]);
      ctx.ui.notify(`Pi VPN expired (7-day window). Run /vpn refresh to extend. Config: ${CONFIG_DIR}`, "warning");
      return;
    }
    // Valid window — ensure wireproxy.conf + start
    const c = ensureWireproxyConf();
    void c;
    const r = await startWireproxy(pi, ctx);
    const running = await isWireproxyRunning(pi);
    updateStatus(ctx, running ? "vpn:on" : "vpn:off");
    updateWidget(ctx, [
      `VPN ${running ? "ON" : "OFF"}`,
      `expiry ${humanRemaining(remainingSec)}`,
      `proxy :${HTTP_PORT} / socks :${SOCKS_PORT}`,
      `/vpn status`
    ]);
    if (!r.ok) {
      ctx.ui.notify(`Pi VPN: ${r.msg}`, "warning");
    } else {
      ctx.ui.notify(`Pi VPN: ${r.msg} — expiry ${humanRemaining(remainingSec)}`, "info");
    }
  });

  pi.on("session_shutdown", async (_event: any, _ctx: any) => {
    // Tunnel lives only while pi runs — stop wireproxy if we started it.
    // If wrapper pi-vpn started it, its trap will also stop it; harmless to attempt.
    try {
      const pid = readPid();
      if (pid && pidAlive(pid) && startedByExtension) {
        try { process.kill(pid, "SIGTERM"); } catch {}
        try { fs.unlinkSync(PID_FILE); } catch {}
      }
    } catch {}
  });
}
